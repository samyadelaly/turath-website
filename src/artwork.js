// 15 — TURATH SCRAMBLE / TYPEWRITER FONT ANIMATION ENGINE
// ============================================================================
/**
 * TURATH Font Scramble & Typewriter Engine
 * - High-end metallic / digital luxury aesthetic
 * - Initial load typewriter/scramble reveal with lock-in
 * - Scroll-linked font scrambling during docking transit
 * - Locks firmly into "TURATH" with crisp kerning & white-space: nowrap !important
 */
export function initTurathScrambleAnimation() {
  const wordmark = document.querySelector('.hero-wordmark, .turath-interpolator');
  if (!wordmark) return null;

  const TARGET_WORD = 'TURATH';
  const SCRAMBLE_GLYPHS = 'TRH7019/\\*+X#_§[]|';
  const FONT_PALETTE = [
    "'Cinzel', serif",
    "'Syne', sans-serif",
    "'Playfair Display', serif",
    "'Space Mono', monospace",
    "'Inter', sans-serif"
  ];
  const BASE_FONT = "'Syne', sans-serif";
  const DOCKED_FONT = "'Cinzel', serif";
  const CHAR_CADENCES = [3, 4, 2, 5, 3, 4];

  // If scramble spans not already populated, initialize them
  let chars = wordmark.querySelectorAll('.scramble-char');
  if (chars.length === 0) {
    wordmark.innerHTML = TARGET_WORD.split('').map(ch =>
      `<span class="scramble-char" data-char="${ch}">${ch}</span>`
    ).join('');
    chars = wordmark.querySelectorAll('.scramble-char');
  }

  let isIntroRunning = false;

  // Trigger high-end metallic/digital scramble on page load
  function runIntroScramble() {
    if (isIntroRunning) return;
    isIntroRunning = true;

    chars.forEach((span, i) => {
      let iterations = 0;
      const maxIterations = 6 + i * 3; // Staggered lock from left to right

      const interval = setInterval(() => {
        if (iterations < maxIterations) {
          const randGlyph = SCRAMBLE_GLYPHS[Math.floor(Math.random() * SCRAMBLE_GLYPHS.length)];
          span.textContent = randGlyph;
          span.style.fontFamily = FONT_PALETTE[Math.floor(Math.random() * FONT_PALETTE.length)];
          iterations++;
        } else {
          clearInterval(interval);
          span.textContent = span.dataset.char || TARGET_WORD[i];
          span.style.fontFamily = BASE_FONT;
          if (i === chars.length - 1) {
            isIntroRunning = false;
          }
        }
      }, 42);
    });
  }

  // Scroll scramble handler called from main.js ScrollTrigger onUpdate
  let scrambleTick = 0;
  let lastScrollY = 0;

  function handleScrollScramble(progress, curScrollY) {
    if (isIntroRunning) return;

    if (progress < 0.05) {
      chars.forEach(ch => {
        ch.style.fontFamily = BASE_FONT;
        if (ch.textContent !== ch.dataset.char) {
          ch.textContent = ch.dataset.char;
        }
      });
    } else if (progress >= 0.85) {
      // Locked when docked into navbar
      chars.forEach(ch => {
        ch.style.fontFamily = DOCKED_FONT;
        if (ch.textContent !== ch.dataset.char) {
          ch.textContent = ch.dataset.char;
        }
      });
    } else {
      // Transit scramble between 0.05 and 0.85
      const deltaY = Math.abs(curScrollY - lastScrollY);
      if (deltaY >= 4) {
        scrambleTick++;
        lastScrollY = curScrollY;
        chars.forEach((ch, idx) => {
          const cadence = CHAR_CADENCES[idx % CHAR_CADENCES.length] || 3;
          if ((scrambleTick + idx * 2) % cadence === 0) {
            const randFont = FONT_PALETTE[Math.floor(Math.random() * FONT_PALETTE.length)];
            ch.style.fontFamily = randFont;
          }
        });
      }
    }
  }

  // Run intro on start only on desktop and after page settles
  if (typeof window !== "undefined" && window.innerWidth >= 1024) {
    setTimeout(runIntroScramble, 1200);
  }

  return {
    triggerScramble: runIntroScramble,
    onScrollProgress: handleScrollScramble
  };
}
